#!/usr/bin/env python3
"""Phase 4 GitOps Auto-Remediation Worker & CLI:
Generates deterministic Git branch names, Terraform remediation files, and Pull Request payloads
from Critic-validated WAFFinding records, enforcing severity/savings guardrails and SHA-256 deduplication.

Usage examples:
  # Preview a GitOps Pull Request plan from a sample finding:
  uv run python scripts/gitops_pr_generator.py --demo
"""

import argparse
import hashlib
import json
from typing import Any

SEVERITY_RANK = {
    "CRITICAL": 4,
    "HIGH": 3,
    "MEDIUM": 2,
    "LOW": 1,
}


def compute_finding_fingerprint(finding: dict[str, Any]) -> str:
    """Computes a deterministic 12-char SHA-256 fingerprint for deduplicating GitOps PRs."""
    raw_key = f"{finding['resource_uri']}|{finding['waf_pillar']}|{finding['waf_principle']}"
    return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()[:12]


def should_open_gitops_pr(
    finding: dict[str, Any],
    min_severity: str = "HIGH",
    min_cost_savings_usd: float = 100.0,
) -> bool:
    """Determines whether a validated finding qualifies for automated Pull Request creation."""
    sev = finding.get("severity", "LOW").upper()
    if SEVERITY_RANK.get(sev, 0) >= SEVERITY_RANK.get(min_severity.upper(), 3):
        return True

    savings = finding.get("estimated_monthly_savings_usd") or 0.0
    if finding.get("waf_pillar") == "COST" and savings >= min_cost_savings_usd:
        return True

    return False


def build_gitops_pr_plan(finding: dict[str, Any], base_branch: str = "main") -> dict[str, Any]:
    """Constructs the Git branch name, file path, HCL content, and PR Markdown body for a finding."""
    fingerprint = compute_finding_fingerprint(finding)
    project_id = finding["project_id"]
    pillar = finding["waf_pillar"].lower()
    severity = finding["severity"]

    branch_name = f"waf-remediation/{project_id}/{pillar}-{fingerprint}"
    target_tf_path = f"remediations/{project_id}/{pillar}_{fingerprint}.tf"

    savings = finding.get("estimated_monthly_savings_usd")
    savings_line = f"**${savings:,.2f} / month**" if savings else "N/A (Security/Reliability hardening)"

    hcl_header = (
        f"# Auto-generated by Autonomous Google Cloud WAF Auditor\n"
        f"# Resource URI : {finding['resource_uri']}\n"
        f"# WAF Pillar   : {finding['waf_pillar']} ({finding['waf_principle']})\n"
        f"# Fingerprint  : {fingerprint}\n\n"
    )

    pr_title = f"fix({project_id}): [{severity}] WAF {finding['waf_pillar']} remediation ({fingerprint})"
    pr_body = f"""## Autonomous Google Cloud Well-Architected Framework Remediation

| Attribute | Value |
| :--- | :--- |
| **Resource URI** | `{finding['resource_uri']}` |
| **Project ID** | `{project_id}` |
| **WAF Pillar** | `{finding['waf_pillar']}` |
| **WAF Core Principle** | **{finding['waf_principle']}** |
| **Severity** | `{severity}` |
| **Estimated Monthly Savings** | {savings_line} |
| **Finding Fingerprint** | `{fingerprint}` |

### Architectural Rationale
{finding['rationale']}

### Proposed Terraform Remediation (`{target_tf_path}`)
```hcl
{finding['terraform_remediation'].strip()}
```

---
*Verified deterministically by `Compliance_Critic` (`python-hcl2` AST + Cloud Asset Inventory URI check).*
"""

    return {
        "fingerprint": fingerprint,
        "base_branch": base_branch,
        "branch_name": branch_name,
        "target_tf_path": target_tf_path,
        "file_content": hcl_header + finding["terraform_remediation"].strip() + "\n",
        "pr_title": pr_title,
        "pr_body": pr_body,
        "labels": ["waf-auto-remediation", f"pillar:{pillar}", f"severity:{severity.lower()}"],
    }


def select_findings_for_gitops(
    findings: list[dict[str, Any]],
    existing_fingerprints: set[str] | None = None,
    min_severity: str = "HIGH",
    min_cost_savings_usd: float = 100.0,
    max_prs_per_run: int = 5,
) -> list[dict[str, Any]]:
    """Filters, deduplicates, and prioritizes findings for Phase 4 GitOps PR creation."""
    seen = set(existing_fingerprints or set())
    qualified = []

    sorted_findings = sorted(
        findings,
        key=lambda f: (
            SEVERITY_RANK.get(f.get("severity", "LOW").upper(), 0),
            f.get("estimated_monthly_savings_usd") or 0.0,
        ),
        reverse=True,
    )

    for finding in sorted_findings:
        if not should_open_gitops_pr(finding, min_severity=min_severity, min_cost_savings_usd=min_cost_savings_usd):
            continue
        fp = compute_finding_fingerprint(finding)
        if fp in seen:
            continue
        seen.add(fp)
        qualified.append(build_gitops_pr_plan(finding))
        if len(qualified) >= max_prs_per_run:
            break

    return qualified


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Phase 4 GitOps Pull Request plans from WAF findings.")
    parser.add_argument("--demo", action="store_true", help="Run a demonstration PR plan for open_ssh_firewall.")
    args = parser.parse_args()

    if args.demo:
        sample_finding = {
            "resource_uri": "//compute.googleapis.com/projects/waf-compliance-hub/global/firewalls/allow-ssh-world",
            "project_id": "waf-compliance-hub",
            "folder_id": "folders/11223344",
            "waf_pillar": "SECURITY",
            "waf_principle": "Implement zero trust",
            "severity": "CRITICAL",
            "compliance_status": "NON_COMPLIANT",
            "rationale": "Firewall rule allow-ssh-world permits unrestricted ingress (0.0.0.0/0) on TCP port 22 with firewall logging disabled.",
            "terraform_remediation": """resource "google_compute_firewall" "allow_ssh_iap" {
  name          = "allow-ssh-world"
  project       = "waf-compliance-hub"
  network       = "prod-vpc"
  direction     = "INGRESS"
  source_ranges = ["35.235.240.0/20"]

  allow {
    protocol = "tcp"
    ports    = ["22"]
  }

  log_config {
    metadata = "INCLUDE_ALL_METADATA"
  }
}""",
            "estimated_monthly_savings_usd": None,
        }
        plan = build_gitops_pr_plan(sample_finding)
        print(json.dumps(plan, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
